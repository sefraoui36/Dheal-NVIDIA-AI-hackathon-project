"""
Challenges endpoints — multi-activity, family + friends.

Rankings use TRUST-VERIFIED totals. Commentary is generated by Nemotron
as a coach (pattern analysis + per-person suggestions).
"""

import json
from datetime import datetime
from pathlib import Path

from fastapi import APIRouter, HTTPException
from pydantic import BaseModel

from app.ai.nemotron_client import (
    COMMENTARY_CACHE,
    generate_challenge_cheer,
)
from app.services.challenge_coach import build_coach_report
from app.services.challenges_service import (
    ACTIVITIES,
    aggregate_challenge,
    aggregate_progress,
    ensure_friend_data,
    get_activity,
    get_or_create_challenge,
    list_activities,
    list_all_challenges_for_user,
)

router = APIRouter(prefix="/challenges", tags=["challenges"])

DATA_DIR = Path(__file__).resolve().parent.parent.parent / "data"
CHALLENGES_DIR = DATA_DIR / "challenges"
CHALLENGES_DIR.mkdir(parents=True, exist_ok=True)


class CreateChallengeRequest(BaseModel):
    creator_id: str
    name: str
    activity: str
    duration_days: int
    participant_ids: list[str]
    friends: list[dict] = []


class CommentaryRequest(BaseModel):
    user_id: str


class CheerRequest(BaseModel):
    user_id: str
    target_user_id: str


def _path(user_id: str) -> Path:
    return CHALLENGES_DIR / f"{user_id}.json"


def _load(user_id: str) -> list[dict]:
    p = _path(user_id)
    if not p.exists():
        return []
    try:
        return json.loads(p.read_text(encoding="utf-8-sig"))
    except (json.JSONDecodeError, UnicodeDecodeError):
        return []


def _save(user_id: str, entries: list[dict]) -> None:
    _path(user_id).write_text(json.dumps(entries, indent=2), encoding="utf-8")


@router.get("/activities")
def activities():
    """Return the list of supported challenge activities."""
    return {"activities": list_activities()}


@router.get("/{user_id}")
def list_challenges(user_id: str):
    return {
        "user_id": user_id,
        "challenges": list_all_challenges_for_user(user_id),
    }


@router.post("")
def create_challenge(req: CreateChallengeRequest):
    if req.activity not in ACTIVITIES:
        raise HTTPException(
            status_code=400, detail=f"Unsupported activity: {req.activity}"
        )

    participants: list[str] = list(req.participant_ids)

    for f in req.friends:
        fid = f.get("id")
        fname = f.get("name", fid)
        if not fid:
            continue
        ensure_friend_data(fid, fname)
        if fid not in participants:
            participants.append(fid)

    if len(participants) < 2:
        raise HTTPException(
            status_code=400, detail="A challenge needs at least 2 participants"
        )

    challenge = get_or_create_challenge(
        creator_id=req.creator_id,
        name=req.name,
        activity=req.activity,
        duration_days=req.duration_days,
        participants=participants,
    )

    for pid in participants:
        entries = _load(pid)
        if not any(e["id"] == challenge["id"] for e in entries):
            entries.append(challenge)
            _save(pid, entries)

    return {"status": "ok", "challenge": challenge}


@router.get("/{challenge_id}/leaderboard")
def leaderboard(challenge_id: str, user_id: str):
    entries = _load(user_id)
    challenge = next((c for c in entries if c["id"] == challenge_id), None)
    if not challenge:
        raise HTTPException(status_code=404, detail="Challenge not found")

    return aggregate_challenge(challenge)


@router.get("/{challenge_id}/progress")
def progress(challenge_id: str, user_id: str):
    """Per-day, per-participant series for the progress chart."""
    entries = _load(user_id)
    challenge = next((c for c in entries if c["id"] == challenge_id), None)
    if not challenge:
        raise HTTPException(status_code=404, detail="Challenge not found")

    return aggregate_progress(challenge)


@router.post("/{challenge_id}/commentary")
def challenge_commentary(challenge_id: str, req: CommentaryRequest):
    """
    Coach's read on the race.

    Cached once per challenge per day — Nemotron is only called the first
    time someone requests the commentary for that challenge on that date.
    """
    entries = _load(req.user_id)
    challenge = next((c for c in entries if c["id"] == challenge_id), None)
    if not challenge:
        raise HTTPException(status_code=404, detail="Challenge not found")

    board = aggregate_challenge(challenge)

    # no data yet — honest starter message, no AI call
    if not board.get("winner") or board["winner"]["verified_total"] == 0:
        return {
            "challenge_id": challenge_id,
            "text": (
                "The challenge has just started — no verified data yet. "
                "Check back once everyone has moved."
            ),
            "per_person": [],
        }

    # ---- per-day cache ----
    today = datetime.utcnow().date().isoformat()
    cache_key = f"{challenge_id}:{today}"
    cached = COMMENTARY_CACHE.get(cache_key)
    if cached:
        return cached

    # build progress series for pattern analysis
    # rule-based coach — no LLM call, always works
    progress_data = aggregate_progress(challenge)
    result = build_coach_report(progress_data, board["activity"])

    payload = {
        "challenge_id": challenge_id,
        "text": result.get("text", "Keep it going, everyone."),
        "per_person": result.get("per_person", []),
    }
    COMMENTARY_CACHE[cache_key] = payload
    return payload


@router.post("/{challenge_id}/cheer")
def challenge_cheer(challenge_id: str, req: CheerRequest):
    """Personal cheer grounded in the participant's actual trend."""
    entries = _load(req.user_id)
    challenge = next((c for c in entries if c["id"] == challenge_id), None)
    if not challenge:
        raise HTTPException(status_code=404, detail="Challenge not found")

    board = aggregate_challenge(challenge)
    target_row = next(
        (r for r in board["leaderboard"] if r["user_id"] == req.target_user_id),
        None,
    )
    if not target_row:
        raise HTTPException(
            status_code=404, detail="Target user not in this challenge"
        )

    progress_data = aggregate_progress(challenge)
    series_row = next(
        (
            s
            for s in progress_data.get("series", [])
            if s["user_id"] == req.target_user_id
        ),
        None,
    )
    daily = series_row["daily"] if series_row else []

    winner = board["winner"]
    activity = board["activity"]

    try:
        result = generate_challenge_cheer(
            target_name=target_row["name"],
            target_total=target_row["verified_total"],
            target_daily=daily,
            leader_name=winner["name"] if winner else "the leader",
            leader_total=winner["verified_total"] if winner else 0,
            activity_label=activity["label"],
            activity_unit=activity["unit"],
        )
    except Exception as e:
        raise HTTPException(
            status_code=502, detail=f"Cheer generation failed: {e}"
        )

    return {
        "challenge_id": challenge_id,
        "target_user_id": req.target_user_id,
        "text": result.get("text", f"Keep going, {target_row['name']}!"),
    }